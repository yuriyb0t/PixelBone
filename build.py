#!/usr/bin/env python3
"""Bundle entry.lua + pixrig/*.lua into one main.lua and package the extension.

Usage: python3 build.py            -> dist/main.lua + dist/pixrig-<ver>.aseprite-extension
Modules keep using require("pixrig.xxx"); inside the bundle `require` is
shadowed by a local loader, so nothing depends on package.path.
"""
import json, os, zipfile

root = os.path.dirname(os.path.abspath(__file__))
mods = ["json", "rig", "skin", "export", "store", "view", "ui"]   # order does not matter (lazy)

out = ["""-- GENERATED by build.py - edit the sources, not this file.
local __loaders = {}
local __loaded = {}
local function __req(name)
  if __loaded[name] == nil then
    local f = __loaders[name]
    if not f then error("pixrig: module not found: " .. name) end
    __loaded[name] = f(__req)
  end
  return __loaded[name]
end
local function __reset()
  for k in pairs(__loaded) do __loaded[k] = nil end
end
"""]
for m in mods:
    src = open(os.path.join(root, "pixrig", m + ".lua"), encoding="utf-8").read()
    out.append('__loaders["pixrig.%s"] = function(require)\n%s\nend\n' % (m, src))
out.append(open(os.path.join(root, "entry.lua"), encoding="utf-8").read())

dist = os.path.join(root, "dist")
os.makedirs(dist, exist_ok=True)
main = os.path.join(dist, "main.lua")
open(main, "w", encoding="utf-8").write("\n".join(out))

pkg = json.load(open(os.path.join(root, "package.json"), encoding="utf-8"))
ext = os.path.join(dist, "%s-%s.aseprite-extension" % (pkg["name"], pkg["version"]))
with zipfile.ZipFile(ext, "w", zipfile.ZIP_DEFLATED) as z:
    z.write(os.path.join(root, "package.json"), "package.json")
    z.write(main, "main.lua")
print("built", ext)
